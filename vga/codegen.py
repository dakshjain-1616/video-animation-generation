"""Codegen stage: the model writes the scene code, the system keeps it honest.

One file, `scenes.tsx`, is generated by the LLM. Before it can reach a render
it must pass, in order:

1. static contract checks (imports, forbidden APIs, required export and keys),
2. `tsc` typecheck under tsconfig.generated.json,
3. a visual legibility check: the middle frame of every scene is rendered and
   measured (blank frame, light-on-paper, dark-on-night).

with every rejection fed back to the model. The per-project Remotion entry is
written here deterministically — the model never writes the player plumbing.

The typecheck scoping note: tsconfig.generated.json covers all projects under
src/generated, so one broken old project needs deleting before new ones
typecheck; the errors say which file is at fault.
"""

