REPO_ROOT = Path(__file__).resolve().parent.parent

ALLOWED_MODULES = {"react", "remotion"}
ALLOWED_IMPORT_PREFIXES = ("../../components/foundation/", "../../lib/", "../../packs/")

FORBIDDEN_PATTERNS: tuple[tuple[str, str], ...] = (
    (r"\bimport\s*\(", "dynamic import()"),
    (r"\brequire\s*\(", "require()"),
    (r"\beval\s*\(", "eval()"),
    (r"new\s+Function", "new Function"),
    (r"\bfetch\s*\(", "fetch()"),
    (r"XMLHttpRequest", "XMLHttpRequest"),
    (r"\bsetTimeout\b|\bsetInterval\b", "timers"),
    (r"localStorage|sessionStorage", "storage"),
    (r"\bwindow\b|\bdocument\b|\bglobalThis\b", "DOM/global access"),
    (r"Math\.random", "Math.random (use seeded primitives)"),
    (r"#[0-9a-fA-F]{3}\b|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{8}\b", "hardcoded hex color (use useTheme tokens)"),
    (r"\bnode:", "node APIs"),
    (r"\bprocess\.", "process"),
    (r"dangerouslySetInnerHTML|<\s*(?:iframe|script|object|embed)\b", "executable external markup"),
    (r'\b(?:src|href)\s*=\s*(?:\{\s*)?["\']https?://|url\(\s*["\']?https?://', "remote media URL (use staged local assets)"),
    (r"\b(?:animation|animationName|transition)\s*:", "CSS animation/transition (use frame-driven styles)"),
)

# `from "x"` and bare `import "x"`; multi-line imports still contain their from.
_FROM_RE = re.compile(r"""from\s+["']([^"']+)["']""")
_SIDE_RE = re.compile(r"""^\s*import\s+["']([^"']+)["']""", re.MULTILINE)
_SCENES_BLOCK_RE = re.compile(r"export const SCENES[^=]*=\s*\{([\s\S]*?)\n\};")
_KEY_RE = re.compile(r"^\s*([A-Za-z_$][\w$]*)\s*:", re.MULTILINE)
# JSX timing props: delay={60}, stagger={100}, duration={50} — seconds, not frames.
_TIMING_RE = re.compile(r"\b(delay|stagger|duration)=\{([0-9]+(?:\.[0-9]+)?)\}")
_FENCE_RE = re.compile(r"```(?:tsx|typescript|ts)?\s*([\s\S]*?)```")
# Observed near-miss: the model reaches for lib/packs under components/.
_NEAR_MISS_RE = re.compile(r"""(["'])\.\./\.\./components/(lib|packs)/""")


def normalize_imports(source: str) -> tuple[str, bool]:
    """Fix the model's known import-path near-misses; returns (source, fixed?)."""
    fixed = _NEAR_MISS_RE.sub(r"\1../../\2/", source)
    return fixed, fixed != source


def normalize_types(source: str) -> tuple[str, bool]:
    """React 19 has no global JSX namespace; tolerate the model's older idiom.

    `JSX.Element` is rewritten to an imported `ReactElement`. This is a type
    spelling, not a behavior change, and it saves a repair round.
    """
    if "JSX.Element" not in source:
        return source, False
    fixed = source.replace("JSX.Element", "ReactElement")
    if not re.search(r"""import\s+type\s*\{[^}]*\bReactElement\b""", fixed):
        fixed = 'import type { ReactElement } from "react";\n' + fixed
    return fixed, True


# Detached hints for the confusions small models keep making; appended to the
# typecheck feedback so every repair round carries the correction with it.
_ERROR_HINTS = {
    "hardcoded hex color": (
        "remove every #hex color literal. Inside a scene component, call useTheme() "
        "and use colors.fg, colors.sub, or colors.accent instead."
    ),
    "on type 'Theme'": (
        "useTheme() returns { pack, surface, colors } — read colors.fg, colors.sub, "
        "colors.accent for the surface's own colors, and pack.palette / pack.fonts for "
        "surface-independent tokens (pack.fonts.display, pack.palette.ink, ...)."
    ),
    "useTheme must be used inside": (
        "call useTheme() only inside components rendered under BodyScene, CardScene "
        "or MediaScene — declare an inner component (e.g. const Body = () => "
        "{const {colors} = useTheme(); return ...}) and render <Body/> from the scene."
    ),
    "Cannot find name 'sctx'": (
        "spring() needs { frame, fps, config } imported from \"remotion\" alongside useCurrentFrame/useVideoConfig."
    ),
    "is not assignable to type 'readonly": "interpolate() input arrays need matching lengths and number literals only.",
    "bleeds off the": (
        "your layout crosses the frame edge: total element width = x + width "
        "(ComparePanel: x + width*2 + 40; KineticHeading at size lg is ~900px wide). "
        "Set x to 96 and keep x + total width within 1920 - 96."
    ),
    "is not assignable to type '400 | 500 | undefined'": (
        "numeric props take numeric literals, not strings (weight={500}, never weight=\"500\")."
    ),
    "Type 'string' is not assignable to type": (
        "props typed as numbers take numeric literals: fontSize={32}, width={400} — never quoted strings."
    ),
}


def error_hints(errors: str) -> str:
    lines = [f"- {hint}" for marker, hint in _ERROR_HINTS.items() if marker in errors]
    return "\n".join(lines)


def generate_scenes(
    storyboard: Storyboard,
    plan: Plan,
    llm: LlmConfig,
    assets: list = (),
    attempts: int = 3,
    review: bool = True,
    review_llm: LlmConfig | None = None,
    diagnostics_sink: Callable[[list[dict]], None] | None = None,
) -> dict:
    """Create the project's scenes.tsx (model) and entry.tsx (template)."""
    scenes_file = code_dir(storyboard.id) / "scenes.tsx"
    reviewer = review_llm or llm
    tried: list[str] = []
    notes: list[str] = []
    review_status = "disabled" if not review else "unavailable"

    def validate_source(raw: str) -> str:
        nonlocal review_status
        tried.append(raw)
        fixed, normalized = normalize_imports(strip_fences(raw))
        if normalized:
            notes.append("import paths normalized to the documented relative form")
        fixed, types_fixed = normalize_types(fixed)
        if types_fixed:
            notes.append("JSX.Element normalized to ReactElement for React 19")
        source = fixed
        errors = contract_errors(source, plan)
        if errors:
            hints = error_hints("\n".join(errors))
            raise ValueError(
                "Contract checks failed (allowed imports: react, remotion, "
                '"../../lib/...", "../../packs/...", '
                '"../../components/foundation/..."):\n- ' + "\n- ".join(errors)
                + ("\nFix hints:\n" + hints if hints else "")
            )
        scenes_file.parent.mkdir(parents=True, exist_ok=True)
        scenes_file.write_text(source + "\n", encoding="utf-8")
        type_errors = typecheck(storyboard.id)
        if type_errors:
            text = "\n".join(type_errors)
            hints = error_hints(text)
            raise ValueError(
                "The code did not typecheck (tsc -p tsconfig.generated.json):\n"
                + text
                + ("\nFix hints:\n" + hints if hints else "")
            )
        # The typecheck cannot see pixels: render the middle of every scene and
        # measure it, so blank scenes and light-on-light text are repaired here,
        # before they can reach the full render.
        visual, stills = visual_issues(storyboard, plan)
        if visual:
            raise ValueError(
                "The rendered frames failed the legibility check:\n- " + "\n- ".join(visual)
            )
        # Pixel stats pass: now a vision model judges composition. A review that
        # cannot run is noted in the report and never blocks the render.
        if review:
            try:
                critique = review_scenes(storyboard, plan, stills, reviewer, assets=assets)
                review_status = "failed" if critique else "passed"
            except InfraError:
                raise
            except Exception as error:
                review_status = "unavailable"
                notes.append(f"vision review skipped: {error}")
                critique = []
            if critique and len(tried) >= attempts:
                # Last attempt: ship it, with the unresolved critique on record.
                notes.extend(f"unresolved review: {line}" for line in critique)
            elif critique:
                raise ValueError("The art director rejected these frames:\n- " + "\n- ".join(critique))
        return source

    diagnostics: list[dict] = []
    def validate(raw: str) -> str:
        try:
            result = validate_source(raw)
        except ValueError as error:
            diagnostics.append({"attempt": len(tried), "pass": False, "errors": str(error)})
            if diagnostics_sink:
                diagnostics_sink(diagnostics)
            else:
                _write_attempt_diagnostics(storyboard.id, diagnostics)
            raise
        diagnostics.append({"attempt": len(tried), "pass": True, "review": review_status})
        if diagnostics_sink:
            diagnostics_sink(diagnostics)
        else:
            _write_attempt_diagnostics(storyboard.id, diagnostics)
        return result

    source = chat_text(llm, _messages(storyboard, plan, assets), validate, attempts, stage="codegen")
    write_snapshot(storyboard, source)
    return {
        "file": relative(scenes_file),
        "attempts": len(tried),
        "pass": True,
        "notes": notes,
        "review": review_status,
    }


def _write_attempt_diagnostics(project_id: str, diagnostics: list[dict]) -> None:
    path = REPO_ROOT / "data" / "projects" / project_id / "code-attempts.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(diagnostics, indent=2) + "\n", encoding="utf-8")


# --- visual legibility check -------------------------------------------------

# Safe-box bleed: content may never cross the stage margin, and in portrait it
# may not sit under the platform's top/bottom UI bands either. A heading placed
# too far right, or a diagram wider than the safe box, spills off-frame and no
# typecheck can see it. The still used for legibility is measured at the four
# unsafe bands: real content there (a luma spread against the band's own
# background) is repair feedback.

BLANK_SPREAD = 4.0  # 10th-90th percentile luma; a blank vignette frame is 0
BLANK_CONTRAST = 45.0
PAPER_BRIGHT_YMAX = 230.0  # paper tokens top out near 216; night chalk is ~240
NIGHT_DARK_YMAX = 110.0
EDGE_SPREAD = 60.0  # band luma spread that counts as content outside the safe box
# Body scenes must put real ink in the bottom third of the visual box. This is
# deliberately low: a single label or line passes; a bare background does not.
FILL_MIN = 0.02
# Mean absolute luma delta between midpoint and 85%. A settled scene with one
# slowly alive element clears this; a frozen hold does not.
MOTION_MIN = 0.6


def visual_issues(storyboard: Storyboard, plan: Plan | None = None) -> tuple[list[str], list[str]]:
    """Render the middle frame of each scene and measure it.

    Returns (issues, still paths) so the vision review can reuse the stills.

    Deterministic pixel statistics, not vision: a scene that draws nothing, or
    draws only light elements on the paper surface, is caught before the full
    render. Passing runs remove these temporary stills; failed runs keep them.

    A composition that throws while rendering is a generated-code bug, so it
    comes back as repair feedback too. Only service/tooling failures
    (ServiceMissing) abort the run.
    """
    from .render import RenderError, render_stills  # local import: no module-level cycle

    board_path = REPO_ROOT / "data" / "projects" / storyboard.id / "storyboard.json"
    if not board_path.exists():
        raise RuntimeError("storyboard.json must be written before the visual check")

    frames: list[int] = []
    start = 0
    for scene in storyboard.scenes:
        local_mid = min(scene.frames - 1, max(4, scene.frames // 2))
        local_late = min(scene.frames - 1, max(local_mid + 1, int(scene.frames * 0.85)))
        local_early = min(local_mid - 1, max(4, int(scene.frames * 0.15)))
        frames.extend((start + local_early, start + local_mid, start + local_late))
        start += scene.frames

    out_dir = REPO_ROOT / "data" / "projects" / storyboard.id / "qa" / "visual"
    try:
        stills = render_stills(str(board_path), frames, str(out_dir))
    except RenderError as error:
        return [
            f"the scenes.tsx crashed the renderer: {error} "
            "(most often: useTheme() called in the top-level scene component — "
            "see the theme rule in the system prompt)"
        ], []
    early_stills = stills[0::3]
    mid_stills = stills[1::3]
    late_stills = stills[2::3]
    portrait = storyboard.height > storyboard.width
    margin = 72 if portrait else 96
    top_band = 180 if portrait else 96
    bottom_band = 340 if portrait else 96
    # Leave a small tolerance inside the nominal margin: a stroke drawn exactly
    # on stage.left legitimately overhangs it by half its width, which is not a
    # user-visible bleed. The bands still catch text or diagrams pushed well
    # outside the safe box.
    side_band = max(32, margin - 24)
    top_band = max(24, top_band - 24)
    bottom_band = max(24, bottom_band - 24)
    safe_top = 180 if portrait else 96
    safe_bottom = storyboard.height - (340 if portrait else 96)
    visual_top = safe_top + (230 if portrait else 190)
    visual_height = safe_bottom - visual_top
    fill_box = (
        margin,
        visual_top + visual_height * 2 / 3,
        storyboard.width - margin * 2,
        visual_height / 3,
    )
    issues: list[str] = []
    for scene, earlier, still, later in zip(storyboard.scenes, early_stills, mid_stills, late_stills):
        issues.extend(_legibility_issues(scene, _luma_stats(still), still))
        for side, size in (
            ("left", side_band), ("right", side_band), ("top", top_band), ("bottom", bottom_band),
        ):
            edge = _edge_stats(still, side, size)
            issues.extend(_edge_issues(scene, side, edge))
        planned = next((s for s in plan.scenes if s.id == scene.id), None) if plan else None
        if scene.kind == "body" and not scene.asset and (planned is None or planned.layout == "diagram"):
            issues.extend(_fill_issues(scene, _fill_fraction(still, scene.surface, fill_box)))
        issues.extend(_motion_issues(scene, _strongest_motion(_motion_delta(earlier, still), _motion_delta(still, later))))
    return issues, list(stills)


def _strongest_motion(*deltas: float | None) -> float | None:
    available = [delta for delta in deltas if delta is not None]
    return max(available) if available else None


def _motion_delta(mid: str, late: str) -> float | None:
    """Mean absolute luma difference between two stills (0 = identical)."""
    result = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", mid, "-i", late,
         "-filter_complex",
         "[0:v][1:v]blend=all_mode=difference,signalstats,metadata=print:file=-",
         "-f", "null", "-"],
        capture_output=True, text=True, timeout=120,
    )
    for line in (result.stderr if result.returncode else result.stdout).splitlines():
        key, _, value = line.partition("=")
        if key.strip().endswith("signalstats.YAVG"):
            try:
                return float(value.strip())
            except ValueError:
                return None
    return None


def _motion_issues(scene, delta: float | None) -> list[str]:
    if delta is None or delta >= MOTION_MIN:
        return []
    return [
        f"scene {scene.id}: the frame looks static across its early, middle and late frames "
        f"(mean delta {delta:.2f}); visibly perform the planned start/action/end sequence. "
        "Use <Alive> only for appropriate ambient motion; a completed action may hold."
    ]


def _fill_fraction(
    path: str,
    surface: str,
    box: tuple[float, float, float, float],
) -> float | None:
    """Fraction of pixels in `box` that are ink against the scene's surface."""
    x, y, width, height = (int(round(value)) for value in box)
    if width <= 0 or height <= 0:
        return None
    threshold = "lt(val,150)" if surface == "paper" else "gt(val,120)"
    result = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", path,
         "-vf", f"crop={width}:{height}:{x}:{y},format=gray,lut=y='if({threshold},255,0)',"
                "signalstats,metadata=print:file=-",
         "-f", "null", "-"],
        capture_output=True, text=True, timeout=120,
    )
    for line in (result.stderr if result.returncode else result.stdout).splitlines():
        key, _, value = line.partition("=")
        if key.strip().endswith("signalstats.YAVG"):
            try:
                return float(value.strip()) / 255.0
            except ValueError:
                return None
    return None


def _fill_issues(scene, fraction: float | None) -> list[str]:
    if fraction is None or fraction >= FILL_MIN:
        return []
    return [
        f"scene {scene.id}: the lower third of the visual box is empty "
        f"({fraction * 100:.1f}% ink); scale the main visual up or center it "
        "lower in stage.visual so it fills the box. Do not add decorative filler."
    ]


def _edge_stats(path: str, side: str, size: int) -> dict[str, float]:
    """Luma stats for an unsafe band at one frame side (left|right|top|bottom)."""
    if side == "left":
        crop = f"{size}:ih:0:0"
    elif side == "right":
        crop = f"{size}:ih:iw-{size}:0"
    elif side == "top":
        crop = f"iw:{size}:0:0"
    else:
        crop = f"iw:{size}:0:ih-{size}"
    result = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error",
         "-i", path, "-vf", f"crop={crop},signalstats,metadata=print:file=-", "-f", "null", "-"],
        capture_output=True, text=True, timeout=120,
    )
    stats: dict[str, float] = {}
    for line in (result.stderr if result.returncode else result.stdout).splitlines():
        key, _, value = line.partition("=")
        if key.strip().startswith("lavfi.signalstats.Y"):
            name = key.strip().split(".")[-1]
            try:
                stats[name] = float(value.strip())
            except ValueError:
                pass
    missing = {"YLOW", "YHIGH"} - set(stats)
    if missing:
        return {}
    return stats


def _edge_issues(scene, side: str, stats: dict[str, float]) -> list[str]:
    if not stats or stats.get("YLOW") is None or stats.get("YHIGH") is None:
        return []
    spread = stats["YHIGH"] - stats["YLOW"]
    # Percentiles catch a broad wash of content; a single clipped headline can
    # occupy less than 10% of the band, so also test the darkest/brightest pixel
    # against the surface's own background.
    paper_ink = scene.surface == "paper" and stats.get("YMIN", 255.0) < 120.0
    night_ink = scene.surface == "night" and stats.get("YMAX", 0.0) > 150.0
    if spread < EDGE_SPREAD and not paper_ink and not night_ink:
        return []
    return [
        f"scene {scene.id}: content is drawn in the unsafe {side} band of the frame "
        f"(luma spread {spread:.0f}); everything must stay inside the stage's safe "
        "box (useStage) — pull x/y/width/height back in"
    ]


def _luma_stats(path: str) -> dict[str, float]:
    """ffmpeg signalstats: luma extremes and central spread for one still.

    YLOW/YHIGH (10th/90th percentiles) are the legibility signal: they prove a
    spread of content, not just an outlier pixel.
    """
    result = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error",
         "-i", path, "-vf", "signalstats,metadata=print:file=-", "-f", "null", "-"],
        capture_output=True, text=True, timeout=120,
    )
    stats: dict[str, float] = {}
    for line in (result.stderr if result.returncode else result.stdout).splitlines():
        # metadata=print writes "frame:0   pts:0 ... lavfi.signalstats.YMIN=216"
        key, _, value = line.partition("=")
        if key.strip().startswith("lavfi.signalstats.Y"):
            name = key.strip().split(".")[-1]
            try:
                stats[name] = float(value.strip())
            except ValueError:
                pass
    missing = {"YMIN", "YMAX", "YAVG", "YLOW", "YHIGH"} - set(stats)
    if missing:
        raise RuntimeError(_ffmpeg_stats_error(missing, path, result.stderr))
    return stats


def _ffmpeg_stats_error(missing: set[str], path: str, stderr: str) -> str:
    detail = stderr.strip().splitlines()[-3:]
    return f"could not measure {', '.join(sorted(missing))} for {path}: {' | '.join(detail)}"


def _legibility_issues(scene, stats: dict[str, float], still_path: str = "") -> list[str]:
    where = f"scene {scene.id}" + (f" (still {still_path})" if still_path else "")
    ymin, ymax, yavg = stats["YMIN"], stats["YMAX"], stats["YAVG"]
    spread = stats["YHIGH"] - stats["YLOW"]  # 10th-90th percentile luma spread
    contrast = ymax - ymin
    if spread < BLANK_SPREAD and contrast < BLANK_CONTRAST:
        return [
            f"{where}: the mid-scene frame is blank (luma spread {spread:.0f}, contrast {contrast:.0f}); "
            "something must be visibly drawn and settled by the middle of the scene"
        ]
    if scene.asset:
        # A media scene shows caller-provided imagery of arbitrary color; the
        # drawn-surface luma rules do not apply. The spread check above still
        # guards against a media file that failed to load.
        return []
    if scene.surface == "paper" and ymax >= PAPER_BRIGHT_YMAX:
        return [
            f"{where}: near-white elements on the paper surface (max luma {ymax:.0f}); "
            "write text with colors.fg/colors.sub (dark ink), never light text on paper"
        ]
    if scene.surface == "night" and ymax < NIGHT_DARK_YMAX:
        return [
            f"{where}: nothing bright on the night surface (max luma {ymax:.0f}); "
            "use colors.fg/colors.accent for the content"
        ]
    return []


def code_dir(project_id: str) -> Path:
    return REPO_ROOT / "src" / "generated" / project_id


def relative(path: Path) -> str:
    return str(path.relative_to(REPO_ROOT))


def strip_fences(raw: str) -> str:
    fenced = _FENCE_RE.search(raw)
    return (fenced.group(1) if fenced else raw).strip()


def contract_errors(source: str, plan: Plan) -> list[str]:
    errors: list[str] = []

    modules = set(_FROM_RE.findall(source)) | set(_SIDE_RE.findall(source))
    for module in sorted(modules):
        if module not in ALLOWED_MODULES and not module.startswith(ALLOWED_IMPORT_PREFIXES):
            errors.append(
                f'import "{module}" is not allowed '
                "(react, remotion, and ../../components/foundation|lib|packs only)"
            )

    for pattern, label in FORBIDDEN_PATTERNS:
        if re.search(pattern, source):
            errors.append(f"forbidden API in generated code: {label}")

    # The house wrappers own the shell, header and heading anchors. Direct use
    # of these primitives is how scenes drift away from the studio layout.
    for primitive in ("SceneShell", "SectionHeader", "KineticHeading", "MediaFrame"):
        if f"<{primitive}" in source:
            errors.append(
                f"do not render <{primitive}> directly in generated code; "
                "use BodyScene, CardScene or MediaScene (and mediaLayout for overlays)"
            )

    # Timing props are seconds; the model keeps writing frame numbers there,
    # which stalls reveals for whole scenes. Absurd values are contract errors.
    for prop, value in _TIMING_RE.findall(source):
        if float(value) >= 5.0:
            errors.append(
                f'{prop}={{{value}}} looks like frames; timing props are SECONDS '
                f"(use values like 0.2-2.5, at 30fps 0.2s = 6 frames)"
            )

    if "export const SCENES" not in source:
        errors.append("missing required export: export const SCENES: Record<string, React.FC>")
        return errors  # without the export, nothing else is worth checking

    _played = {scene.id for scene in plan.scenes}
    keys = set(_scene_keys(source))
    for scene_id in sorted(_played - keys):
        errors.append(f'SCENES is missing the key "{scene_id}"')
    for key in sorted(keys - _played):
        errors.append(f'SCENES has an unexpected key "{key}"; write exactly the plan\'s scenes')
    return errors


def _scene_keys(source: str) -> list[str]:
    block = _SCENES_BLOCK_RE.search(source)
    if not block:
        return []
    return _KEY_RE.findall(block.group(1))


def typecheck(project_id: str) -> list[str]:
    """Typecheck this project only; returns errors scoped to its generated code.

    A repo-wide typecheck made every run pay for every old project and let a
    stale project burn repair attempts. A per-project tsconfig still pulls in
    the shared foundation through imports, but stops parsing unrelated scenes.
    """
    config = REPO_ROOT / f".tsconfig.{project_id}.json"
    config.write_text(
        json.dumps(
            {
                "extends": "./tsconfig.json",
                "compilerOptions": {"noUnusedLocals": False, "noUnusedParameters": False},
                "include": [f"src/generated/{project_id}"],
                "exclude": ["node_modules"],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    try:
        result = subprocess.run(
            ["npx", "tsc", "-p", str(config), "--pretty", "false"],
            cwd=str(REPO_ROOT),
            capture_output=True,
            text=True,
            timeout=600,
        )
    except subprocess.TimeoutExpired:
        return ["npx tsc --noEmit timed out after 600s"]
    finally:
        config.unlink(missing_ok=True)
    if result.returncode == 0:
        output = ""
    else:
        output = (result.stderr + "\n" + result.stdout).strip()
    lines = [line for line in output.splitlines() if line.strip()]
    scoped = [
        line for line in lines
        if f"src/generated/{project_id}/" in line or f"src/generated/{project_id}\\" in line
    ]
    if lines and not scoped:
        # A broken *other* generated project must not block this one or burn
        # model repair attempts: it cannot be imported by this project.
        if all("src/generated/" in line for line in lines):
            return []
        # Anything else (bad tsconfig, missing deps) is environment, not code.
        raise InfraError(
            "Project typecheck failed outside the generated code; see the first errors:\n"
            + "\n".join(lines[:10])
        )
    return scoped[:40]


def _messages(storyboard: Storyboard, plan: Plan, assets: list) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": CODE_SYSTEM.replace("__FORMAT__", format_rules(storyboard.width, storyboard.height))},
        {"role": "user", "content": _code_brief(storyboard, plan, assets)},
    ]


def _code_brief(storyboard: Storyboard, plan: Plan, assets: list) -> str:
    asset_by_id = {asset.id: asset for asset in assets}
    scenes = []
    planned = {scene.id: scene for scene in plan.scenes}
    for scene in storyboard.scenes:
        block = (
            f"- id: {scene.id}  kind: {scene.kind}  surface: {scene.surface}  "
            f"title: {scene.title}\n  seconds: {scene.seconds:.2f} (the Sequence enforces the "
            "length; design the content to fill it meaningfully)"
        )
        block += f"\n  layout: {planned[scene.id].layout} (canvas: CanvasScene; diagram: BodyScene; card: CardScene; media: MediaScene)"
        if planned[scene.id].visual:
            block += f"\n  visual (build this): {planned[scene.id].visual}"
        if planned[scene.id].motion:
            beats = planned[scene.id].motion
            block += (f"\n  motion start: {beats['start']}"
                      f"\n  motion action (implement this state change): {beats['action']}"
                      f"\n  motion end (complete by 75% and hold): {beats['end']}")
        if scene.narration:
            block += (
                f'\n  narrator says: "{scene.narration}" — reveal elements in the order the '
                "line mentions them; do not repeat the line as on-screen text"
            )
        if scene.asset:
            asset = asset_by_id.get(scene.asset)
            if asset is None:  # unreachable: plan repair guarantees membership
                block += f"\n  asset: {scene.asset}"
            else:
                kind = "animated image" if asset.animated else asset.kind
                block += f"\n  asset: {asset.id} ({kind}) — THE PROTAGONIST OF THIS SCENE"
                if asset.staged:
                    block += f'\n  staged file (pass verbatim: asset="{asset.staged}")'
                else:
                    block += "\n  no file: reconstruct with TweetCard/HeadlineCard below"
                if asset.caption:
                    block += f"\n  handle/attribution: {asset.caption}"
                if asset.source:
                    block += f"\n  source line: {asset.source}"
                if asset.content:
                    block += f'\n  text (verbatim, quote exactly): "{asset.content}"'
                if asset.kind == "clip":
                    block += f"\n  startAt: {asset.start_at} seconds into the clip"
        scenes.append(block)
    from .research import research_brief

    return f"""Idea: {plan.idea}
Angle: {plan.angle}
Audience: {plan.audience}
Video title: {plan.title}

{research_brief(plan.research)}

Scenes in play order:
{"\n".join(scenes)}

Write the complete scenes.tsx file now. Rules from the system prompt apply:
one BodyScene/CardScene/MediaScene/CanvasScene wrapper per scene, tokens from useTheme
(inside the wrapper), seeded primitives, and the SCENES export with exactly the
scene ids above as keys, in play order."""


def write_entry(storyboard: Storyboard) -> Path:
    """The player plumbing: sequences in play order from the storyboard."""
    meta = "\n".join(
        f"  {{ id: {json.dumps(scene.id)}, frames: {scene.frames} }}," for scene in storyboard.scenes
    )
    template = (
        _ENTRY.replace("__SCENES_META__", meta)
        .replace("__PACK__", storyboard.pack or "editorial-ink")
        .replace("__TOTAL__", str(storyboard.frames()))
        .replace("__FPS__", str(storyboard.fps))
        .replace("__WIDTH__", str(storyboard.width))
        .replace("__HEIGHT__", str(storyboard.height))
    )
    path = code_dir(storyboard.id) / "entry.tsx"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(template, encoding="utf-8")
    return path


def write_snapshot(storyboard: Storyboard, source: str) -> None:
    """Keep a copy of the final generated code next to the project's artifacts."""
    project = REPO_ROOT / "data" / "projects" / storyboard.id / "code"
    project.mkdir(parents=True, exist_ok=True)
    (project / "scenes.tsx").write_text(source + "\n", encoding="utf-8")


